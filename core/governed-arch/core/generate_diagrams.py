def format_governed_interface_contracts(mod_toml: dict, global_locks: dict, module_name: str, counter: SectionCounter) -> str:
    """Merges Public API and Interface Contracts into a single governed section."""
    exposed = mod_toml.get("public_api", {}).get("exposed", [])
    local_locks = mod_toml.get("interface_lock", {})
    all_locks = {**global_locks, **local_locks}
    
    # Filter locks that belong to this module
    locks_by_file = {}
    for path, data in all_locks.items():
        if path.startswith(module_name):
            locks_by_file[path] = data

    if not exposed and not locks_by_file:
        return ""
    
    sections = [f"<h2>{counter.next()}. Governed Interface Contracts</h2>"]
    sections.append("<p>Interfaces listed below are governed by signature locks. Exposing an API implies a mandatory lock.</p>")

    # Create lookup from full locked name to its spec and path
    locked_name_to_spec = {}
    for path, data in locks_by_file.items():
        for func_name in data.get("locked_functions", []):
            locked_name_to_spec[func_name] = (path, func_name, data.get("specs", {}).get(func_name))

    # A helper to check if a name is public (exposed or class method of exposed class)
    def check_is_public(name: str) -> bool:
        name_lower = name.lower()
        exposed_lower = [e.lower() for e in exposed]
        if name_lower in exposed_lower:
            return True
        if "." in name:
            parts = name_lower.split(".")
            if parts[0] in exposed_lower:
                return True
        return False

    # Build the grouped structure
    governed_groups = {}
    
    # 1. Process all locked functions
    for func_name, (path, _, spec) in locked_name_to_spec.items():
        if not check_is_public(func_name):
            continue
            
        if "." in func_name:
            class_name, method_name = func_name.split(".", 1)
            # Find existing class group case-insensitively
            matched_class = class_name
            for g_name in governed_groups.keys():
                if g_name.lower() == class_name.lower():
                    matched_class = g_name
                    break
            if matched_class not in governed_groups:
                governed_groups[matched_class] = {
                    "type": "class",
                    "path": path,
                    "description": "",
                    "methods": {}
                }
            governed_groups[matched_class]["methods"][method_name] = spec
        else:
            spec_desc = spec.get("description", "") if spec else ""
            governed_groups[func_name] = {
                "type": "function",
                "path": path,
                "description": spec_desc,
                "spec": spec
            }

    # 2. Add exposed items that aren't locked but exist in exposed
    for exp_name in exposed:
        matched_group_key = None
        for g_name in governed_groups.keys():
            if g_name.lower() == exp_name.lower():
                matched_group_key = g_name
                break
                
        if matched_group_key is None:
            has_methods_locked = any(k.lower().startswith(exp_name.lower() + ".") for k in locked_name_to_spec.keys())
            if not has_methods_locked:
                guessed_path = "Unknown"
                if locks_by_file:
                    guessed_path = list(locks_by_file.keys())[0]
                
                # Check case-insensitively if exp_name has a direct lock spec
                spec = None
                matched_lock_key = None
                for k in locked_name_to_spec.keys():
                    if k.lower() == exp_name.lower():
                        matched_lock_key = k
                        break
                if matched_lock_key:
                    guessed_path, _, spec = locked_name_to_spec[matched_lock_key]
                
                spec_desc = spec.get("description", "") if spec else ""
                governed_groups[exp_name] = {
                    "type": "class" if exp_name[0].isupper() else "function",
                    "path": guessed_path,
                    "description": spec_desc,
                    "spec": spec
                }

    # 3. Pull descriptions from spec keys matching parent name directly.
    # We use a fallback cascade to prevent empty descriptions:
    # Spec Description -> Returns Description -> File Lock Reason
    # We allow case-insensitive matching here solely to map instance singletons (e.g., lowercase "notifier")
    # to their parent classes (e.g., uppercase "Notifier") in visual reports.
    for name, group in governed_groups.items():
        for path, data in locks_by_file.items():
            specs = data.get("specs", {})
            for spec_key in specs.keys():
                if spec_key.lower() == name.lower():
                    spec_data = specs[spec_key]
                    desc = spec_data.get("description", "")
                    if not desc:
                        desc = spec_data.get("returns", {}).get("description", "")
                    if desc:
                        group["description"] = desc

        # Fallback: Use the file lock's general reason if no specific function/class description is found
        if not group["description"]:
            for path, data in locks_by_file.items():
                locked_fns_lower = [k.lower() for k in data.get("locked_functions", [])]
                if name.lower() in locked_fns_lower or any(k.startswith(name.lower() + ".") for k in locked_fns_lower):
                    group["description"] = data.get("reason", "")
                    break

    sections.append("<table><thead><tr><th>Function/Class</th><th>Source File</th><th>Description</th></tr></thead><tbody>")
    
    for name in sorted(governed_groups.keys()):
        group = governed_groups[name]
        path = group["path"]
        desc = group["description"]
        
        # Determine if there are detailed specs in the group
        has_specs = False
        if group["type"] == "class" and "methods" in group:
            has_specs = any(group["methods"].values())
        elif "spec" in group and group["spec"]:
            has_specs = True
            
        if path != "Unknown":
            display_link = f'<a href="#contract-{safe_id(name)}"><code>{name}</code></a>' if has_specs else f'<code>{name}</code>'
            sections.append(f'<tr><td>{display_link}</td><td><code>{esc(path)}</code></td><td>{esc(desc)}</td></tr>')
        else:
            sections.append(f'<tr><td><code>{esc(name)}</code></td><td><small><em>Unknown</em></small></td><td>{esc(desc)}</td></tr>')
            
    sections.append("</tbody></table>")

    # Detailed specs for those that have them
    for name in sorted(governed_groups.keys()):
        group = governed_groups[name]
        path = group["path"]
        
        has_specs = False
        if group["type"] == "class" and "methods" in group:
            has_specs = any(group["methods"].values())
        elif "spec" in group and group["spec"]:
            has_specs = True
            
        if not has_specs:
            continue
            
        sections.append(f"<h3 id=\"contract-{safe_id(name)}\">Contract: <code>{esc(name)}</code></h3>")
        sections.append(f'<div class="lock-reason"><strong>Location:</strong> <code>{esc(path)}</code></div>')
        
        if group["type"] == "class" and "methods" in group:
            # Render each method
            for method_name, spec in sorted(group["methods"].items()):
                if not spec:
                    continue
                sections.append(f"<h4>Method: <code>{esc(method_name)}</code></h4>")
                sections.append('<div class="spec-box">')
                if "params" in spec:
                    sections.append('<table><thead><tr><th>Parameter</th><th>Type</th><th>Default</th><th>Description</th></tr></thead><tbody>')
                    for p in spec["params"]:
                        sections.append(f'<tr><td><span class="badge badge-param">{esc(p.get("name"))}</span></td>')
                        sections.append(f'<td><span class="badge badge-type">{esc(p.get("type"))}</span></td>')
                        sections.append(f'<td><code>{esc(p.get("default"))}</code></td>')
                        sections.append(f'<td>{esc(p.get("description"))}</td></tr>')
                    sections.append('</tbody></table>')
                
                ret = spec.get("returns", {})
                if ret:
                    sections.append(f'<p><strong>Returns:</strong> <code>{esc(ret.get("type"))}</code> - {esc(ret.get("description"))}</p>')
                    if "required_keys" in ret:
                        sections.append(f'<p><strong>Required Keys:</strong> <code>{esc(json.dumps(ret["required_keys"]))}</code></p>')
                    if "required_columns" in ret:
                        sections.append(f'<p><strong>Required Columns:</strong> <code>{esc(json.dumps(ret["required_columns"]))}</code></p>')
                sections.append('</div>')
        else:
            # Standalone function or enum spec
            spec = group["spec"]
            sections.append('<div class="spec-box">')
            if "params" in spec:
                sections.append('<table><thead><tr><th>Parameter</th><th>Type</th><th>Default</th><th>Description</th></tr></thead><tbody>')
                for p in spec["params"]:
                    sections.append(f'<tr><td><span class="badge badge-param">{esc(p.get("name"))}</span></td>')
                    sections.append(f'<td><span class="badge badge-type">{esc(p.get("type"))}</span></td>')
                    sections.append(f'<td><code>{esc(p.get("default"))}</code></td>')
                    sections.append(f'<td>{esc(p.get("description"))}</td></tr>')
                sections.append('</tbody></table>')
            
            ret = spec.get("returns", {})
            if ret:
                sections.append(f'<p><strong>Returns:</strong> <code>{esc(ret.get("type"))}</code> - {esc(ret.get("description"))}</p>')
                if "required_keys" in ret:
                    sections.append(f'<p><strong>Required Keys:</strong> <code>{esc(json.dumps(ret["required_keys"]))}</code></p>')
                if "required_columns" in ret:
                    sections.append(f'<p><strong>Required Columns:</strong> <code>{esc(json.dumps(ret["required_columns"]))}</code></p>')
            sections.append('</div>')
    
    return "".join(sections)


def format_invariants(invariants: dict, module_name: str, counter: SectionCounter) -> str:
    if not invariants:
        return ""
    
    sections = [f"<h2>{counter.next()}. Semantic Invariants (🔴 Red Lines)</h2>"]
    
    for cat, data in invariants.items():
        sections.append(f"<h3>Category: {esc(cat.replace('_', ' ').title())}</h3><ul>")
        for rule in data.get("rules", []):
            if isinstance(rule, str):
                sections.append(f"<li>{esc(rule)}</li>")
            else:
                rule_id = rule.get("id", "")
                sections.append(f'<li id="invariant-{safe_id(rule_id)}"><span class="invariant-id">[{esc(rule_id)}]</span> {esc(rule.get("desc"))}')
                if "test_ref" in rule:
                    sections.append(f'<br/><small>Verified by: <code>{esc(rule["test_ref"])}</code></small>')
                sections.append("</li>")
        sections.append("</ul>")
    
    return "".join(sections)


