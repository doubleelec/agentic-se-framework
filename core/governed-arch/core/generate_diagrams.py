def discover_all_modules(base_dir: Path, submodules_list: list[str]) -> set[str]:
    """Recursively discover all module directories that have a module.toml."""
    discovered = set()
    for sub in submodules_list:
        sub_path = base_dir / sub
        if sub_path.is_dir():
            mod_toml = sub_path / "module.toml"
            if mod_toml.exists():
                rel_path = sub_path.relative_to(PROJECT_ROOT).as_posix()
                discovered.add(rel_path)
                with open(mod_toml, "rb") as f:
                    try:
                        cfg = tomllib.load(f)
                        inner_subs = cfg.get("module", {}).get("submodules", [])
                        discovered.update(discover_all_modules(sub_path, inner_subs))
                    except Exception:
                        pass
    return discovered


def get_module_depends_on(module_name: str, arch: dict) -> list[str]:
    """Get the depends_on list for any module (top-level or submodule)."""
    if "/" not in module_name:
        cfg = arch.get("module", {}).get(module_name, {})
        return list(cfg.get("depends_on", []))
    
    parts = module_name.split("/")
    parent_name = "/".join(parts[:-1])
    child_name = parts[-1]
    
    parent_toml_path = PROJECT_ROOT / parent_name / "module.toml"
    if parent_toml_path.exists():
        with open(parent_toml_path, "rb") as f:
            try:
                p_cfg = tomllib.load(f)
                sub_cfg = p_cfg.get("submodule", {}).get(child_name, {})
                return list(sub_cfg.get("depends_on", [])) + list(sub_cfg.get("external_depends", []))
            except Exception:
                pass
    return []


