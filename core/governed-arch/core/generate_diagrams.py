def _design_steps_list(steps: list) -> str:
    items = []
    for i, step in enumerate(steps):
        items.append(f"<li><strong>{esc(step.get('title', ''))}</strong> — {esc(step.get('desc', ''))}</li>")
    return "<ol>" + "".join(items) + "</ol>"


def _build_design_link_lookup(mod_toml: dict, module_name: str, global_locks: dict | None = None, global_invariants: dict | None = None) -> dict:
    """Sets of ref names / invariant ids that resolve to real HTML anchors.

    Mirrors format_governed_interface_contracts anchor selection: a ref is
    live iff its owning class/function is exposed AND carries at least one
    non-empty lock spec; an invariant id is live iff declared in the module
    or the architecture-wide invariant rules.
    """
    exposed = [e.lower() for e in mod_toml.get("public_api", {}).get("exposed", [])]
    all_locks = dict(global_locks or {})
    all_locks.update(mod_toml.get("interface_lock", {}))
    specs_map = {}
    for path, data in all_locks.items():
        if path.startswith(module_name):
            for spec_key, spec in data.get("specs", {}).items():
                specs_map[spec_key.lower()] = spec

    def ref_ok(r: str) -> bool:
        cls = str(r).split(".")[0].lower()
        if cls not in exposed:
            return False
        if "." in str(r):
            return any(k.startswith(cls + ".") and specs_map[k] for k in specs_map)
        return any(k == cls and specs_map[k] for k in specs_map)

    inv_ok: set[str] = set()
    for inv in (global_invariants or {}, mod_toml.get("invariant", {})):
        for cat, data in inv.items():
            for rule in data.get("rules", []):
                if isinstance(rule, dict) and rule.get("id"):
                    inv_ok.add(rule["id"])

    return {"ref_ok": ref_ok, "inv_ok": inv_ok}


def format_design_section(mod_toml: dict, counter: SectionCounter, lookup: dict | None = None) -> str:
    """Render the optional [[design.flows]] chapter (Core Flows & Algorithms)."""
    flows = mod_toml.get("design", {}).get("flows", [])
    if not flows:
        return ""
    sections = [f"<h2>{counter.next()}. Core Flows & Algorithms</h2>"]

    for block in flows:
        block_id = block.get("id", "")
        anchor = f' id="design-{safe_id(block_id)}"' if block_id else ""
        sections.append(f"<h3{anchor}>{esc(block.get('title', ''))}</h3>")
        if block.get("summary"):
            sections.append(f"<p><em>{esc(block['summary'])}</em></p>")
        steps = block.get("steps", [])
        if not steps:
            continue
        kind = block.get("kind", "")
        if kind == "flow":
            mmd = _design_flow_mermaid(block, lookup)
            sections.append(f'<div class="mermaid">{mmd}</div>' if mmd else _design_steps_list(steps))
        elif kind == "gates":
            sections.append(_design_gates_table(steps, lookup))
        elif kind == "priority":
            sections.append(_design_priority_table(steps, lookup))
        elif kind == "principles":
            sections.append(_design_principles_cards(steps, lookup))
        else:
            sections.append(_design_steps_list(steps))
    return "".join(sections)


