# Mermaid IDs cannot contain "/", ".", or "-". Use a deterministic scheme.
def safe_id(name: str) -> str:
    return name.replace("/", "_").replace(".", "_").replace("-", "_")


class SectionCounter:
    def __init__(self, start=1):
        self.count = start
    
    def next(self):
        val = self.count
        self.count += 1
        return val


# ── Mermaid Generation ──────────────────────────────────────────────

def _get_dynamic_font_size(node_count: int, is_internal: bool = False) -> str:
    """
    Dynamic font size to compensate for Mermaid's auto-scaling.
    4-tier staircase (unified internal/external):
    - Small (<=5): 16px
    - Medium (6-8): 20px
    - Large (9-12): 28px
    - X-Large (>12): 52px
    """
    if node_count <= 5:
        return "16px"
    elif node_count <= 8:
        return "20px"
    elif node_count <= 12:
        return "28px"
    else:
        return "64px"


def _load_architecture() -> dict:
    with open(ARCHITECTURE_FILE, "rb") as f:
        return tomllib.load(f)


def _load_module_toml(module_dir: Path) -> dict:
    """Load a single module's module.toml. Returns {} if absent."""
    mt = module_dir / "module.toml"
    if not mt.exists():
        return {}
    with open(mt, "rb") as f:
        return tomllib.load(f)


def _get_timestamp() -> str:
    import datetime
    return datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")


def esc(value: Any) -> str:
    if value is None:
        return ""
    return html.escape(str(value), quote=True)


def esc_br(value: Any) -> str:
    return esc(value).replace("\n", "<br/>")


def generate_architecture_full_mmd(arch: dict) -> str:
    """Top-level module dependency graph from architecture.toml [module.*]."""
    modules = arch.get("module", {})
    if not modules:
        return ""

    node_count = len(modules)
    font_size = _get_dynamic_font_size(node_count)

    lines = ["graph TD", "    %% Top-Level Architecture (Design Intent)"]
    for mod_name, cfg in modules.items():
        desc = cfg.get("description", "")
        if desc:
            desc_lines = [l.strip() for l in desc.splitlines() if l.strip()]
            non_header_lines = [l for l in desc_lines if not (l.startswith("[") and l.endswith("]"))]
            desc = non_header_lines[0] if non_header_lines else desc_lines[0]
        if len(desc) > 24:
            desc = desc[:22] + "…"
        lines.append(
            f'    {safe_id(mod_name)}["<b>{mod_name}</b><br/>'
            f'<small><i>{desc}</i></small>"]:::module'
        )

    lines.append("\n    %% Declared dependencies")
    for mod_name, cfg in modules.items():
        for dep in cfg.get("depends_on", []):
            if dep in modules:
                lines.append(f"    {safe_id(mod_name)} --> {safe_id(dep)}")

    lines.append(f"\n    classDef module fill:#F3E5F5,stroke:#8E24AA,"
                 f"stroke-width:2px,color:#4A148C,font-size:{font_size},font-weight:bold;")
    return "\n".join(lines)


def format_metadata_section(mod_toml: dict, counter: SectionCounter) -> str:
    """Format the [module] section metadata into HTML."""
    module_meta = mod_toml.get("module", {})
    if not module_meta:
        return ""
    
    sections = [f"<h2>{counter.next()}. Responsibility & Data Flow</h2>"]
    
    if "description" in module_meta:
        desc = esc_br(module_meta["description"])
        sections.append(f"<h3>Responsibility</h3><p>{desc}</p>")
    
    consumers = module_meta.get("consumers", [])
    if consumers:
        sections.append("<h3>Consumers</h3><ul>")
        for c in consumers:
            sections.append(f"<li>{esc(c)}</li>")
        sections.append("</ul>")
    
    data_flow = module_meta.get("data_flow", "")
    if data_flow:
        df_html = esc_br(data_flow)
        sections.append(f"<h3>Data Flow</h3><p>{df_html}</p>")
        
    return "".join(sections)


def generate_module_internal_mmd(module_name: str, mod_toml: dict) -> str:
    """Diagram for internal submodule dependencies."""
    module_dir = PROJECT_ROOT / module_name
    # Use submodules list for discovery if available, else fallback to keys of submodule section
    entities = mod_toml.get("module", {}).get("submodules", [])
    sub_rules = mod_toml.get("submodule", {})
    
    if not entities and not sub_rules:
        return ""

    all_entities = set(entities) | set(sub_rules.keys())
    external_entities = set()
    for v in sub_rules.values():
        for dep in v.get("depends_on", []):
            all_entities.add(dep)
        for dep in v.get("internal_depends", []):
            all_entities.add(dep)
        for dep in v.get("external_depends", []):
            external_entities.add(dep)

    node_count = len(all_entities) + len(external_entities)
    font_size = _get_dynamic_font_size(node_count, is_internal=True)

    lines = [f"graph TD", f"    %% {module_name} — Architecture & Dependencies"]

    def label(e: str) -> str:
        if e.endswith(".py"): return e
        if (module_dir / e).is_dir(): return e + "/"
        return e

    for e in sorted(all_entities):
        eid = f"{safe_id(module_name)}_sub_{safe_id(e)}"
        lines.append(f"    {eid}[\"{label(e)}\"]:::internal")

    # Edges
    for src, cfg in sub_rules.items():
        deps = list(cfg.get("depends_on", [])) + list(cfg.get("internal_depends", []))
        for dep in deps:
            src_id = f"{safe_id(module_name)}_sub_{safe_id(src)}"
            dep_id = f"{safe_id(module_name)}_sub_{safe_id(dep)}"
            lines.append(f"    {src_id} --> {dep_id}")
            
        # Draw external_depends as dashed lines to external nodes
        ext_deps = list(cfg.get("external_depends", []))
        for dep in ext_deps:
            src_id = f"{safe_id(module_name)}_sub_{safe_id(src)}"
            dep_id = f"{safe_id(module_name)}_ext_{safe_id(dep)}"
            if dep_id not in lines:
                lines.append(f"    {dep_id}[\"<small><i>{dep}</i></small>\"]:::external")
            lines.append(f"    {src_id} -.-> {dep_id}")


        lines.append(f"\n    classDef internal fill:#E3F2FD,stroke:#1E88E5,stroke-width:2px,color:#0D47A1,font-size:{font_size};")
    lines.append(f"    classDef external fill:#FFF3E0,stroke:#FB8C00,stroke-width:2px,stroke-dasharray:5 5,color:#E65100,font-size:{font_size};")
    return "\n".join(lines)


def generate_module_external_mmd(module_name: str, arch: dict) -> str:
    """Diagram for external module-level dependencies."""
    external_deps = [d for d in get_module_depends_on(module_name, arch) if d != module_name]
    if not external_deps:
        return ""

    node_count = len(external_deps) + 1
    mod_font_size = _get_dynamic_font_size(node_count)
    # External nodes use a slightly smaller font than the primary module node
    ext_font_size = _get_dynamic_font_size(node_count, is_internal=True)

    lines = [f"graph TD", f"    %% {module_name} — External Dependencies"]
    
    # Root node for the current module
    lines.append(f"    {safe_id(module_name)}[\"<b>{module_name}</b>\"]:::module")

    for dep in external_deps:
        lines.append(f"    {safe_id(module_name)} --> {safe_id(dep)}")
        lines.append(f"    {safe_id(dep)}:::external")

    lines.append(f"\n    classDef module fill:#F3E5F5,stroke:#8E24AA,stroke-width:2px,color:#4A148C,font-size:{mod_font_size},font-weight:bold;")
    lines.append(f"    classDef external fill:#FFF3E0,stroke:#FB8C00,stroke-width:2px,stroke-dasharray:5 5,color:#E65100,font-size:{ext_font_size};")

    return "\n".join(lines)


